// Separately implemented outer LXMF paper-URI transport checks.
// Ratspeak verifies/decrypts the encrypted message using the recipient identity.
export const MAX_PAPER_BYTES = 2210;
const MIN_PAPER_BYTES = 112;
const hex = (bytes) => Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
const base64 = (bytes) =>
  btoa(String.fromCharCode(...bytes))
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');
function checkSize(bytes) {
  if (bytes.length < MIN_PAPER_BYTES)
    throw new Error('This paper link is incomplete. Copy the complete lxm:// link from Ratspeak.');
  if (bytes.length > MAX_PAPER_BYTES)
    throw new Error(
      'This paper message is too large. Ratspeak paper messages allow up to 2,210 encoded message bytes.',
    );
}
export function paperUriFromBytes(bytes) {
  checkSize(bytes);
  return 'lxm://' + base64(bytes);
}
export function parsePaperUri(text) {
  if (typeof text !== 'string' || text.length > 16384)
    throw new Error('This paper link is too large. Copy a paper link generated by Ratspeak.');
  const raw = text.trim();
  if (!/^lxm:\/\//i.test(raw))
    throw new Error(
      'Paste a complete lxm:// paper link from Ratspeak, or choose its saved QR image.',
    );
  // Match upstream's transport normalization without touching encrypted bytes.
  const data = raw
    .slice(6)
    .replace(/[\/\t\n\r\f\v ]/g, '')
    .replace(/=+$/, '');
  if (!data || !/^[A-Za-z0-9_-]+$/.test(data) || data.length % 4 === 1)
    throw new Error('This paper link has invalid data. Copy the complete link from Ratspeak.');
  let bytes;
  try {
    bytes = Uint8Array.from(atob(data.replace(/-/g, '+').replace(/_/g, '/')), (c) =>
      c.charCodeAt(0),
    );
  } catch {
    throw new Error('This paper link has invalid data. Copy the complete link from Ratspeak.');
  }
  if (base64(bytes) !== data)
    throw new Error('This paper link is damaged. Copy the complete link from Ratspeak.');
  checkSize(bytes);
  return { text: 'lxm://' + data, bytes, destination: hex(bytes.slice(0, 16)) };
}
